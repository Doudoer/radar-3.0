CREATE TABLE IF NOT EXISTS pbx_call_logs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  uniqueid VARCHAR(64) NOT NULL,
  direction ENUM('inbound','outbound','internal') NOT NULL DEFAULT 'inbound',
  status ENUM('ringing','answered','missed','ended') NOT NULL DEFAULT 'ringing',
  caller_number VARCHAR(64) NOT NULL,
  caller_name VARCHAR(120) NULL,
  destination VARCHAR(64) NULL,
  answered_by_ext VARCHAR(32) NULL,
  client_id INT UNSIGNED NULL,
  client_name VARCHAR(160) NULL,
  order_id VARCHAR(64) NULL,
  order_code VARCHAR(64) NULL,
  duration_seconds INT NOT NULL DEFAULT 0,
  billsec_seconds INT NOT NULL DEFAULT 0,
  started_at DATETIME NOT NULL,
  answered_at DATETIME NULL,
  ended_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY pbx_call_logs_uniqueid (uniqueid),
  INDEX pbx_call_logs_status_started (status, started_at),
  INDEX pbx_call_logs_direction_started (direction, started_at),
  INDEX pbx_call_logs_caller (caller_number)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
